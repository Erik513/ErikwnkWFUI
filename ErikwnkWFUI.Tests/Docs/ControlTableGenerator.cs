using System.Drawing;
using System.Globalization;
using System.Reflection;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using System.Windows.Forms;
using System.Xml.Linq;
using ErikwnkWFUI.Styles;

namespace ErikwnkWFUI.Tests.Docs;

/// <summary>
/// Writes docs/CONTROLS.md: for every control and window of the library its own public properties (type, default, description), events and
/// methods, and the factory methods of UIStyles that make it. Everything comes from the built library (reflection, a fresh control for the
/// defaults, the XML documentation); only what cannot be read from there - the standard properties that a control ignores, a factory class that
/// does not carry the name of the control - comes from docs/control-notes.json. ControlTableTests keeps the file current.
/// </summary>
internal static class ControlTableGenerator
{
    private static readonly string[] Namespaces = { "ErikwnkWFUI.Controls", "ErikwnkWFUI.Forms" };

    public static string FindRepositoryRoot()
    {
        for (DirectoryInfo? directory = new DirectoryInfo(AppContext.BaseDirectory); directory != null; directory = directory.Parent)
        {
            if (File.Exists(Path.Combine(directory.FullName, "ErikwnkWFUI.sln")))
                return directory.FullName;
        }

        throw new InvalidOperationException("ErikwnkWFUI.sln was not found above " + AppContext.BaseDirectory);
    }

    public static IReadOnlyList<Type> GetControlTypes()
    {
        return typeof(UIStyles).Assembly.GetExportedTypes()
            .Where(type => typeof(Control).IsAssignableFrom(type) && !type.IsAbstract && type.Namespace != null && Namespaces.Contains(type.Namespace))
            .OrderBy(type => type.Namespace, StringComparer.Ordinal)
            .ThenBy(type => type.Name, StringComparer.Ordinal)
            .ToList();
    }

    public static string Build()
    {
        string root = FindRepositoryRoot();
        Assembly library = typeof(UIStyles).Assembly;
        XmlDocumentation docs = XmlDocumentation.Load(Path.ChangeExtension(library.Location, ".xml"));
        Dictionary<string, ControlNotes> notes = LoadNotes(Path.Combine(root, "docs", "control-notes.json"));
        List<Type> factories = typeof(UIStyles).GetNestedTypes(BindingFlags.Public).Where(t => t.IsAbstract && t.IsSealed).OrderBy(t => t.Name, StringComparer.Ordinal).ToList();
        IReadOnlyList<Type> controls = GetControlTypes();

        // The defaults are those of the dark theme with the blue accent, whatever the machine or an earlier test left.
        UIColors.ApplyTheme(UIThemes.Dark);
        UIColors.SetAccent(UIAccentColors.Blue);

        try
        {
            StringBuilder text = new StringBuilder();
            text.AppendLine("# Controls and their settings");
            text.AppendLine();
            text.AppendLine("<!-- Generated by ErikwnkWFUI.Tests (ControlTableGenerator). Do not edit: run tools/Update-ControlTable.ps1. -->");
            text.AppendLine();
            text.AppendLine("What every control and window of the library has of its own: properties (the default is that of a new control in the dark theme with the blue");
            text.AppendLine("accent; `-` where it depends on the screen or is not a plain value), events and methods, and the `UIStyles` factory methods that make it. A control keeps");
            text.AppendLine("everything else of its standard WinForms base class; the properties it **ignores** (draws its own way) are listed per control. A type without a");
            text.AppendLine("constructor that takes no parameters shows the defaults of its standard factory called with its default arguments. After the controls come the other");
            text.AppendLine("public types (helpers, static entry points, enumerations) and at the end the factory classes.");
            text.AppendLine();
            text.AppendLine("## Index");
            text.AppendLine();
            text.AppendLine("| Control | Namespace | Factory class |");
            text.AppendLine("|---|---|---|");

            foreach (Type type in controls)
            {
                string? factory = FindFactory(type, factories, notes);
                text.AppendLine($"| [{type.Name}](#{Anchor(type)}){(type.GetCustomAttribute<ObsoleteAttribute>() != null ? " (obsolete)" : "")} | {type.Namespace!.Replace("ErikwnkWFUI.", "")} | {(factory == null ? "-" : "`UIStyles." + factory + "`")} |");
            }

            foreach (Type type in controls)
                AppendControl(text, type, docs, notes, factories);

            AppendOtherTypes(text, docs, controls);

            text.AppendLine();
            text.AppendLine("## UIStyles factory classes");
            text.AppendLine();

            foreach (Type factory in factories)
                AppendFactory(text, factory, docs);

            return text.ToString().Replace("\r\n", "\n");
        }
        finally
        {
            UIColors.ApplyTheme(UIThemes.Dark);
            UIColors.SetAccent(UIAccentColors.Blue);
        }
    }

    // ---- one control

    private static void AppendControl(StringBuilder text, Type type, XmlDocumentation docs, Dictionary<string, ControlNotes> notes, List<Type> factories)
    {
        notes.TryGetValue(type.Name, out ControlNotes? note);

        text.AppendLine();
        text.AppendLine($"## {type.Name}");
        text.AppendLine();
        text.AppendLine($"`{type.Namespace}.{type.Name}` - based on `{type.BaseType?.Name}`");
        text.AppendLine();

        ObsoleteAttribute? obsolete = type.GetCustomAttribute<ObsoleteAttribute>();

        if (obsolete != null)
            text.AppendLine("**Obsolete:** " + obsolete.Message).AppendLine();

        string summary = docs.Summary("T:" + type.FullName);

        if (summary.Length > 0)
            text.AppendLine(summary).AppendLine();

        string? factoryName = FindFactory(type, factories, notes);

        if (factoryName != null)
            text.AppendLine($"Made by `UIStyles.{factoryName}` (see the end of this file).").AppendLine();

        if (note?.Ignored != null && note.Ignored.Length > 0)
            text.AppendLine("Ignored standard properties (drawn the library's way): " + string.Join(", ", note.Ignored.Select(name => "`" + name + "`")) + ".").AppendLine();

        if (!string.IsNullOrWhiteSpace(note?.Notes))
            text.AppendLine(note!.Notes).AppendLine();

        object? instance = TryCreate(type);
        string? madeBy = null;

        if (instance == null)
            instance = TryCreateByFactory(type, factories, out madeBy);

        if (madeBy != null)
            text.AppendLine($"The defaults below are those of `{madeBy}`: the type has no constructor without parameters.").AppendLine();

        try
        {
            AppendProperties(text, type, docs, instance);
            AppendEvents(text, type, docs);
            AppendMethods(text, type, docs);
        }
        finally
        {
            (instance as IDisposable)?.Dispose();
        }
    }

    private static void AppendProperties(StringBuilder text, Type type, XmlDocumentation docs, object? instance)
    {
        PropertyInfo[] properties = type
            .GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly)
            .Where(property => property.GetIndexParameters().Length == 0)
            .OrderBy(property => property.Name, StringComparer.Ordinal)
            .ToArray();

        if (properties.Length == 0)
            return;

        text.AppendLine("| Property | Type | Default | Access | Description |");
        text.AppendLine("|---|---|---|---|---|");

        foreach (PropertyInfo property in properties)
        {
            string access = property.CanWrite && property.SetMethod!.IsPublic ? "get, set" : "get";
            string description = docs.Summary("P:" + type.FullName + "." + property.Name);
            ObsoleteAttribute? obsolete = property.GetCustomAttribute<ObsoleteAttribute>();

            if (obsolete != null)
                description = "**Obsolete:** " + obsolete.Message + " " + description;

            text.AppendLine($"| `{property.Name}` | {TypeName(property.PropertyType)} | {DefaultOf(property, instance)} | {access} | {Cell(description)} |");
        }

        text.AppendLine();
    }

    private static void AppendEvents(StringBuilder text, Type type, XmlDocumentation docs)
    {
        EventInfo[] events = type
            .GetEvents(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly)
            .OrderBy(e => e.Name, StringComparer.Ordinal)
            .ToArray();

        if (events.Length == 0)
            return;

        text.AppendLine("| Event | Handler | Description |");
        text.AppendLine("|---|---|---|");

        foreach (EventInfo e in events)
            text.AppendLine($"| `{e.Name}` | {TypeName(e.EventHandlerType!)} | {Cell(docs.Summary("E:" + type.FullName + "." + e.Name))} |");

        text.AppendLine();
    }

    private static void AppendMethods(StringBuilder text, Type type, XmlDocumentation docs)
    {
        MethodInfo[] methods = type
            .GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly)
            .Where(method => !method.IsSpecialName && method.GetBaseDefinition().DeclaringType == method.DeclaringType)
            .OrderBy(method => method.Name, StringComparer.Ordinal)
            .ThenBy(method => method.GetParameters().Length)
            .ToArray();

        if (methods.Length == 0)
            return;

        text.AppendLine("| Method | Description |");
        text.AppendLine("|---|---|");

        foreach (MethodInfo method in methods)
            text.AppendLine($"| `{Signature(method)}` | {Cell(docs.Summary(MethodId(method)))} |");

        text.AppendLine();
    }

    // ---- the factories

    private static string? FindFactory(Type control, List<Type> factories, Dictionary<string, ControlNotes> notes)
    {
        if (notes.TryGetValue(control.Name, out ControlNotes? note) && !string.IsNullOrEmpty(note.Factory))
            return note.Factory;

        // CheckBox -> CheckBoxes, Button -> Buttons, TextField -> (named in the notes).
        foreach (Type factory in factories)
        {
            if (factory.Name == control.Name + "s" || factory.Name == control.Name + "es")
                return factory.Name;
        }

        return null;
    }

    private static void AppendFactory(StringBuilder text, Type factory, XmlDocumentation docs)
    {
        text.AppendLine($"### UIStyles.{factory.Name}");
        text.AppendLine();

        string summary = docs.Summary("T:" + factory.FullName!.Replace('+', '.'));

        if (summary.Length > 0)
            text.AppendLine(summary).AppendLine();

        MethodInfo[] methods = factory
            .GetMethods(BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly)
            .Where(method => !method.IsSpecialName)
            .OrderBy(method => method.Name, StringComparer.Ordinal)
            .ThenBy(method => method.GetParameters().Length)
            .ToArray();

        if (methods.Length == 0)
        {
            text.AppendLine("(no methods)").AppendLine();

            return;
        }

        text.AppendLine("| Method | Description |");
        text.AppendLine("|---|---|");

        foreach (MethodInfo method in methods)
            text.AppendLine($"| `{Signature(method, withDefaults: true)}` | {Cell(docs.Summary(MethodId(method)))} |");

        text.AppendLine();
    }

    // ---- the other public types

    private static void AppendOtherTypes(StringBuilder text, XmlDocumentation docs, IReadOnlyList<Type> controls)
    {
        Type[] others = typeof(UIStyles).Assembly.GetExportedTypes()
            .Where(type => !type.IsNested && !controls.Contains(type) && !typeof(Delegate).IsAssignableFrom(type))
            .OrderBy(type => type.Namespace, StringComparer.Ordinal)
            .ThenBy(type => type.Name, StringComparer.Ordinal)
            .ToArray();

        text.AppendLine();
        text.AppendLine("## Other public types");
        text.AppendLine();
        text.AppendLine("Helpers, static entry points and the like that are not controls. The enumerations follow with their values.");
        text.AppendLine();
        text.AppendLine("| Type | Kind | Namespace | Description |");
        text.AppendLine("|---|---|---|---|");

        foreach (Type type in others.Where(type => !type.IsEnum))
            text.AppendLine($"| `{type.Name}`{(type.GetCustomAttribute<ObsoleteAttribute>() != null ? " (obsolete)" : "")} | {KindOf(type)} | {type.Namespace!.Replace("ErikwnkWFUI.", "")} | {Cell(docs.Summary("T:" + type.FullName))} |");

        text.AppendLine();
        text.AppendLine("| Enumeration | Values | Description |");
        text.AppendLine("|---|---|---|");

        foreach (Type type in others.Where(type => type.IsEnum))
            text.AppendLine($"| `{type.Name}`{(type.GetCustomAttribute<ObsoleteAttribute>() != null ? " (obsolete)" : "")} | {string.Join(", ", Enum.GetNames(type).Select(name => "`" + name + "`"))} | {Cell(docs.Summary("T:" + type.FullName))} |");
    }

    private static string KindOf(Type type)
    {
        if (type.IsInterface)
            return "interface";

        if (type.IsValueType)
            return "struct";

        if (type.IsAbstract && type.IsSealed)
            return "static class";

        return type.IsAbstract ? "abstract class" : "class";
    }

    // ---- reading the types

    private static object? TryCreate(Type type)
    {
        try
        {
            return type.GetConstructor(Type.EmptyTypes) != null ? Activator.CreateInstance(type) : null;
        }
        catch
        {
            return null;
        }
    }

    // For a type without a constructor that takes no parameters (the progress bar, the windows): the standard factory that returns this type (or the
    // standard control it derives from, which the progress bar's factory does), called with its default arguments (a required text gets an empty one).
    private static object? TryCreateByFactory(Type type, List<Type> factories, out string? madeBy)
    {
        madeBy = null;

        IEnumerable<(Type Factory, MethodInfo Method)> candidates = factories
            .SelectMany(factory => factory.GetMethods(BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly).Select(method => (Factory: factory, Method: method)))
            .Where(candidate => candidate.Method.ReturnType.IsAssignableFrom(type) && candidate.Method.Name.StartsWith("Create", StringComparison.Ordinal) && candidate.Method.Name.EndsWith("Standard", StringComparison.Ordinal))
            .OrderBy(candidate => candidate.Method.GetParameters().Count(parameter => !parameter.HasDefaultValue));

        foreach ((Type factory, MethodInfo method) in candidates)
        {
            ParameterInfo[] parameters = method.GetParameters();
            object?[] arguments = parameters.Select(parameter => parameter.HasDefaultValue ? parameter.DefaultValue : parameter.ParameterType == typeof(string) ? "" : null).ToArray();

            try
            {
                object? instance = method.Invoke(null, arguments);

                if (instance != null && !type.IsInstanceOfType(instance))
                {
                    (instance as IDisposable)?.Dispose();

                    continue;
                }

                if (instance != null)
                {
                    string required = string.Join(", ", parameters.Where(parameter => !parameter.HasDefaultValue).Select(_ => "\"\""));
                    madeBy = $"UIStyles.{factory.Name}.{method.Name}({required})";

                    return instance;
                }
            }
            catch
            {
                // the next candidate
            }
        }

        return null;
    }

    // A plain value only: what a new control has on a machine of any screen scaling. Sizes, fonts, positions and objects depend on the screen.
    private static string DefaultOf(PropertyInfo property, object? instance)
    {
        if (instance == null || !property.CanRead || property.GetMethod!.GetParameters().Length != 0)
            return "-";

        Type type = property.PropertyType;

        if (!(type.IsPrimitive || type.IsEnum || type == typeof(string) || type == typeof(Color) || type == typeof(decimal)))
            return "-";

        try
        {
            object? value = property.GetValue(instance);

            return value switch
            {
                null => "`null`",
                string text => text.Length == 0 ? "`\"\"`" : "`\"" + text.Replace("|", "\\|") + "\"`",
                bool flag => flag ? "`true`" : "`false`",
                Color color => "`" + (color.IsEmpty ? "Empty" : color.IsNamedColor ? color.Name : "#" + color.R.ToString("X2") + color.G.ToString("X2") + color.B.ToString("X2")) + "`",
                IFormattable number => "`" + number.ToString(null, CultureInfo.InvariantCulture) + "`",
                _ => "`" + value + "`"
            };
        }
        catch
        {
            return "-";
        }
    }

    private static string TypeName(Type type)
    {
        return "`" + PlainTypeName(type) + "`";
    }

    // The name as C# writes it: the keywords (bool, string ...), T? for a nullable value and the arguments of a generic type the same way.
    private static string PlainTypeName(Type type)
    {
        Type? nullable = Nullable.GetUnderlyingType(type);

        if (nullable != null)
            return PlainTypeName(nullable) + "?";

        if (type.IsGenericType)
            return type.Name.Split('`')[0] + "<" + string.Join(", ", type.GetGenericArguments().Select(PlainTypeName)) + ">";

        return type switch
        {
            _ when type == typeof(bool) => "bool",
            _ when type == typeof(int) => "int",
            _ when type == typeof(string) => "string",
            _ when type == typeof(double) => "double",
            _ when type == typeof(float) => "float",
            _ when type == typeof(decimal) => "decimal",
            _ when type == typeof(void) => "void",
            _ when type == typeof(object) => "object",
            _ when type == typeof(long) => "long",
            _ when type == typeof(short) => "short",
            _ when type == typeof(byte) => "byte",
            _ when type == typeof(char) => "char",
            _ when type == typeof(uint) => "uint",
            _ when type == typeof(ulong) => "ulong",
            _ => type.Name
        };
    }

    private static string Signature(MethodInfo method, bool withDefaults = false)
    {
        IEnumerable<string> parameters = method.GetParameters().Select(parameter =>
        {
            string text = PlainTypeName(parameter.ParameterType) + " " + parameter.Name;

            if (withDefaults && parameter.HasDefaultValue)
                text += " = " + FormatDefault(parameter.DefaultValue);

            return text;
        });

        return method.Name + "(" + string.Join(", ", parameters) + ")";
    }

    private static string FormatDefault(object? value)
    {
        return value switch
        {
            null => "null",
            string text => "\"" + text + "\"",
            bool flag => flag ? "true" : "false",
            IFormattable number => number.ToString(null, CultureInfo.InvariantCulture),
            _ => value.ToString() ?? ""
        };
    }

    private static string MethodId(MethodInfo method)
    {
        string name = "M:" + method.DeclaringType!.FullName!.Replace('+', '.') + "." + method.Name;
        ParameterInfo[] parameters = method.GetParameters();

        if (parameters.Length == 0)
            return name;

        return name + "(" + string.Join(",", parameters.Select(parameter => XmlTypeName(parameter.ParameterType))) + ")";
    }

    private static string XmlTypeName(Type type)
    {
        if (type.IsByRef)
            return XmlTypeName(type.GetElementType()!) + "@";

        if (type.IsArray)
            return XmlTypeName(type.GetElementType()!) + "[]";

        if (type.IsGenericType)
        {
            string name = type.GetGenericTypeDefinition().FullName!.Split('`')[0].Replace('+', '.');

            return name + "{" + string.Join(",", type.GetGenericArguments().Select(XmlTypeName)) + "}";
        }

        return type.FullName!.Replace('+', '.');
    }

    private static string Anchor(Type type)
    {
        return type.Name.ToLowerInvariant();
    }

    private static string Cell(string text)
    {
        return text.Replace("|", "\\|").Replace("\n", " ");
    }

    private static Dictionary<string, ControlNotes> LoadNotes(string path)
    {
        if (!File.Exists(path))
            return new Dictionary<string, ControlNotes>();

        JsonSerializerOptions options = new JsonSerializerOptions { PropertyNameCaseInsensitive = true, ReadCommentHandling = JsonCommentHandling.Skip, AllowTrailingCommas = true };

        return JsonSerializer.Deserialize<Dictionary<string, ControlNotes>>(File.ReadAllText(path), options) ?? new Dictionary<string, ControlNotes>();
    }

    private sealed class ControlNotes
    {
        public string[]? Ignored { get; set; }
        public string? Notes { get; set; }
        public string? Factory { get; set; }
    }

    // ---- the XML documentation of the library

    private sealed class XmlDocumentation
    {
        private readonly Dictionary<string, XElement> _members;

        private XmlDocumentation(Dictionary<string, XElement> members)
        {
            _members = members;
        }

        public static XmlDocumentation Load(string path)
        {
            Dictionary<string, XElement> members = new Dictionary<string, XElement>(StringComparer.Ordinal);

            if (File.Exists(path))
            {
                foreach (XElement member in XDocument.Load(path).Descendants("member"))
                {
                    string? name = (string?)member.Attribute("name");

                    if (name != null)
                        members[name] = member;
                }
            }

            return new XmlDocumentation(members);
        }

        // The first part of the summary as one line of plain text.
        public string Summary(string id)
        {
            if (!_members.TryGetValue(id, out XElement? member))
                return "";

            XElement? summary = member.Element("summary");

            if (summary == null)
                return "";

            StringBuilder text = new StringBuilder();

            foreach (XNode node in summary.Nodes())
                Append(text, node);

            return Regex.Replace(text.ToString(), @"\s+", " ").Trim();
        }

        private static void Append(StringBuilder text, XNode node)
        {
            if (node is XText plain)
            {
                text.Append(plain.Value);
            }
            else if (node is XElement element)
            {
                if (element.Name == "see" || element.Name == "seealso")
                {
                    string? cref = (string?)element.Attribute("cref");
                    string? langword = (string?)element.Attribute("langword");

                    if (langword != null)
                        text.Append('`').Append(langword).Append('`');
                    else if (cref != null)
                        text.Append('`').Append(ShortName(cref)).Append('`');
                }
                else if (element.Name == "paramref")
                {
                    text.Append('`').Append((string?)element.Attribute("name")).Append('`');
                }
                else if (element.Name == "c" || element.Name == "code")
                {
                    text.Append('`').Append(element.Value).Append('`');
                }
                else
                {
                    foreach (XNode child in element.Nodes())
                        Append(text, child);
                }
            }
        }

        private static string ShortName(string cref)
        {
            string name = cref.Length > 2 && cref[1] == ':' ? cref.Substring(2) : cref;
            int parenthesis = name.IndexOf('(');

            if (parenthesis >= 0)
                name = name.Substring(0, parenthesis);

            // A nested factory class keeps its outer name (UIStyles.CheckBoxes), a plain type or member is named by its last part.
            int styles = name.IndexOf("UIStyles.", StringComparison.Ordinal);

            if (styles >= 0)
                return name.Substring(styles);

            int dot = name.LastIndexOf('.');

            return dot >= 0 ? name.Substring(dot + 1) : name;
        }
    }
}
